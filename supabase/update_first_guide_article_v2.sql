<h3>自分のプロフィール</h3>
<p>自分のページの「プロフィールを編集」から更新できます。得意分野や実績をしっかり書いておくと、案件の相談や紹介につながりやすくなります。X・note・Instagram・ウェブサイトのリンクを登録すると、ページにボタンで表示されます。</p>
<p><img src="/guide/06-profile-edit.jpg" alt="プロフィールの編集。写真もここで設定できます"></p>
<p><em>▲ プロフィールの編集。写真もここで設定できます</em></p>

<h3>実務従事ポイント</h3>
<p>自分のページの「実務従事更新ポイント獲得履歴」で、実務従事の記録を追加できます。活動内容・日付・ポイントを入力しておくと、ホームに進捗として表示されます。何がポイントになるかは、ホームの「実務ポイント獲得リスト」を見てください。</p>
<p><img src="/guide/10b-member-points.jpg" alt="自分のページの獲得履歴。「追加」から記録します"></p>
<p><em>▲ 自分のページの獲得履歴。「追加」から記録します</em></p>

<h3>メッセージを送る</h3>
<p>相手のページの「Slack でメッセージ」を押すと、Slack のダイレクトメッセージが開きます。</p>

<h2>7. ビジカレnote</h2>
<p>メンバーが書いた記事や、運営からのお知らせが、カテゴリーごとに並んでいます。「診断士合格後の教科書」シリーズや各種コラムはここにあります。</p>
<ul>
<li>カテゴリー名を押すと、そのカテゴリーの記事一覧が開きます。</li>
<li>自分でも記事を書けます。「記事の作成」からタイトル・カテゴリー・本文を入れて公開してください。カバー画像はタイトルから AI で生成できます。</li>
</ul>
<p><img src="/guide/08-note.jpg" alt="ビジカレnote。カテゴリーごとに記事が並びます"></p>
<p><em>▲ ビジカレnote。カテゴリーごとに記事が並びます</em></p>


<h2>8. 活動写真</h2>
<p>イベントや勉強会の写真をカテゴリーごとにまとめています。自分で撮った写真もアップロードできるので、参加した回の写真をぜひ共有してください。</p>

<h2>9. アイデア</h2>
<p>思いついたことや気づきを短いメモとして残せる場所です。メンバーがコメントを付けられるほか、メモを AI でコラムの下書きや動画の台本に広げることもできます。「いつか記事にしたい」ネタの置き場として使ってください。</p>

<h2>10. AI に聞く</h2>
<p>コミュニティの情報をもとに答える AI アシスタントです。「〇〇に詳しいメンバーは？」「この前の勉強会で話していた内容は？」のように、探しものや相談に使えます。</p>

<h2>11. 設定</h2>
<ul>
<li><strong>通知</strong> — 新着メッセージ・メンション・リアクション・イベント・新メンバーの通知を、それぞれオン／オフできます。</li>
<li><strong>通知音</strong> — 通知が届いたときに音を鳴らすかどうか。</li>
<li><strong>実務従事の更新期限</strong> — ここに日付を入れると、ホームのポイントブロックに期限までの進捗が出ます。</li>
</ul>
<p><img src="/guide/07b-settings-deadline.jpg" alt="設定の「実務従事の更新期限」"></p>
<p><em>▲ 設定の「実務従事の更新期限」</em></p>


<h2>12. 困ったときは</h2>
<ul>
<li><strong>ログインを求められる</strong> — 「Slackでログイン」をやり直してください。Slack アプリにログイン済みの端末なら、そのまま許可するだけで入れます。</li>
<li><strong>表示が古い</strong> — 一度ページを再読み込みしてください。</li>
<li><strong>それでも解決しない</strong> — チャットで運営（にのみー）にご連絡ください。</li>
</ul>

