<h2>1. まず最初にやること（3つ）</h2>
<ol>
<li><strong>Slack でログインする</strong> — ログイン画面の「Slackでログイン」を押し、ビジカレの Slack ワークスペースで許可します。パスワードは不要です。</li>
<li><strong>プロフィールを入力する</strong> — 「メンバー」→ 自分の名前 →「プロフィールを編集」から、都道府県・所属・得意分野などを書きます。X や note などのリンクも登録できます。</li>
<li><strong>実務従事の更新期限を登録する</strong> — 「設定」→「実務従事の更新期限」に日付を入れると、ホームに期限までのポイント進捗が表示されます。</li>
</ol>
