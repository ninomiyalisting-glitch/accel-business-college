<h2>3. チャット</h2>
<p>ビジカレの Slack と連携しています。チャンネルごとの投稿をアプリで読めて、アプリから投稿やリアクションもできます。Slack を開かなくても、ここだけで会話に参加できます。</p>
<ul>
<li>左（スマホでは一覧）からチャンネルを選びます。</li>
<li>画面上部の検索アイコンから、過去の投稿を検索できます。</li>
<li>投稿はそのまま Slack にも届くので、Slack 派の方とも同じ場所で会話できます。</li>
</ul>
<p><img src="/guide/04-chat.jpg" alt="チャット。左でチャンネルを選び、下の欄から投稿します"></p>
<p><em>▲ チャット。左でチャンネルを選び、下の欄から投稿します</em></p>


<h2>4. 動画ライブラリ</h2>
<p>勉強会やセミナーの録画がまとまっています。フォルダやタグで探せるので、「あのとき話していたテーマ」を後から見直すのに使ってください。参加できなかった回のキャッチアップにも便利です。</p>
<p><img src="/guide/11-videos.jpg" alt="動画ライブラリ"></p>
<p><em>▲ 動画ライブラリ</em></p>


<h2>5. イベント・勉強会</h2>
<p>イベントの一覧と、参加の意思表示ができます。</p>
<ul>
<li><strong>調整中</strong>のイベントには候補日が並んでいます。参加できる日に回答してください。回答が集まると開催日が決まります。</li>
<li><strong>開催決定</strong>のイベントは、日時と内容を確認して参加します。</li>
<li>自分で勉強会を開きたいときは「イベントの作成」から候補日を入れて作れます。</li>
</ul>
<p><img src="/guide/09-events.jpg" alt="イベント一覧。「日程調整中」のものは候補日に回答してください"></p>
<p><em>▲ イベント一覧。「日程調整中」のものは候補日に回答してください</em></p>


<h2>6. メンバー</h2>
<p>コミュニティ全員のプロフィールが見られます。名前・地域・得意分野で検索できるので、「この分野に詳しい人は誰だろう」というときに使ってください。</p>
